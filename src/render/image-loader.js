/**
 * Resolves PNG keys through the manifest and caches decoded WebP images and pending loads.
 * Depends on browser Image/idle APIs; exports createImageLoader and its preload API.
 * @module render/image-loader
 */

/**
 * Create an independent image cache shared by the preview and thumbnail fallback.
 * Failed loads are evicted so later requests can retry.
 * @param {object} [options]
 * @param {import("../types.js").OutfitPreset[]} options.outfitPresets
 * @param {import("../types.js").SpriteManifest} options.manifest
 * @param {(error: Error) => void} [options.onError=console.error]
 */
export function createImageLoader({ outfitPresets, manifest, onError = console.error } = {}) {
  // In-flight loads and decoded images are kept apart, so code that needs an image can never
  // receive a promise by mistake.
  /** @type {Map<string, Promise<HTMLImageElement>>} */
  const pending = new Map();
  /** @type {Map<string, HTMLImageElement>} */
  const loaded = new Map();

  // Catalog `source` paths point at the Photoshop exports. The app actually loads the
  // optimized WebP generated by scripts/optimize-sprites.py, found through the manifest.
  function getManifestEntry(source) {
    const entry = manifest.sprites[source];
    if (!entry) {
      throw new Error(`No optimized sprite for ${source}. Run: python scripts/optimize-sprites.py`);
    }
    return entry;
  }

  /**
   * Reuse a decoded image or an in-flight load for the stable PNG source key.
   * A failed load is forgotten, so calling again retries it.
   * @param {string} source
   * @returns {Promise<HTMLImageElement>} Always a promise, even for a cached image.
   */
  function loadImage(source) {
    const image = loaded.get(source);
    if (image) {
      return Promise.resolve(image);
    }

    const inFlight = pending.get(source);
    if (inFlight) {
      return inFlight;
    }

    const promise = new Promise((resolve, reject) => {
      const entry = getManifestEntry(source);
      const element = new Image();
      element.onload = () => resolve(element);
      element.onerror = () => reject(new Error(`Could not load image asset: ${entry.file}`));
      element.src = entry.file;
    }).then(
      (element) => {
        loaded.set(source, element);
        pending.delete(source);
        return element;
      },
      (error) => {
        pending.delete(source);
        throw error;
      },
    );

    pending.set(source, promise);
    return promise;
  }

  /**
   * Read a decoded sprite without starting a load; geometry uses document pixels.
   * @param {string} source
   * @returns {import("../types.js").Sprite | undefined} Undefined until decoded.
   */
  function getSprite(source) {
    const image = loaded.get(source);
    if (!image) {
      return undefined;
    }

    const { x, y, width, height } = manifest.sprites[source];
    return { image, x, y, width, height, scale: manifest.settings.scale };
  }

  /**
   * List preset sources that are not decoded yet. Loads still in flight count as missing, so
   * callers wait for them (loadImage returns the load already running) instead of drawing early.
   * @param {import("../types.js").OutfitPreset} preset
   * @returns {string[]}
   */
  function getMissingSourcesForPreset(preset) {
    const missing = [];
    for (const item of preset.items) {
      if (!loaded.has(item.source)) {
        missing.push(item.source);
      }
    }
    return missing;
  }

  function preloadPresetAssets(preset) {
    for (const item of preset.items) {
      Promise.resolve(loadImage(item.source)).catch((error) => {
        onError(error);
      });
    }
  }

  /**
   * Warm nearby presets in both directions, wrapping around the preset list.
   * @param {import("../types.js").OutfitPreset} preset
   * @param {number} [distance=2]
   * @returns {void} Background errors are forwarded to onError.
   */
  function preloadAdjacentOutfits(preset, distance = 2) {
    const currentIndex = outfitPresets.findIndex((entry) => String(entry.id) === String(preset.id));
    if (currentIndex < 0) {
      return;
    }

    for (let step = 1; step <= distance; step++) {
      const nextIndex = (currentIndex + step) % outfitPresets.length;
      const previousIndex = (currentIndex - step + outfitPresets.length) % outfitPresets.length;
      preloadPresetAssets(outfitPresets[nextIndex]);
      preloadPresetAssets(outfitPresets[previousIndex]);
    }
  }

  /**
   * Schedule all wearable sources in idle chunks, with a timer fallback.
   * @returns {void} Background errors are forwarded to onError.
   */
  function preloadAllOutfitsInBackground() {
    const allSources = [
      ...new Set(outfitPresets.flatMap((preset) => preset.items.map((item) => item.source))),
    ];
    let cursor = 0;
    const chunkSize = 6;
    const schedule =
      "requestIdleCallback" in window
        ? (callback) => window.requestIdleCallback(callback, { timeout: 280 })
        : (callback) => window.setTimeout(callback, 0);

    const loadChunk = () => {
      const end = Math.min(cursor + chunkSize, allSources.length);
      for (; cursor < end; cursor++) {
        Promise.resolve(loadImage(allSources[cursor])).catch((error) => {
          onError(error);
        });
      }

      if (cursor < allSources.length) {
        schedule(loadChunk);
      }
    };

    schedule(loadChunk);
  }

  return {
    loadImage,
    getSprite,
    getMissingSourcesForPreset,
    preloadAdjacentOutfits,
    preloadAllOutfitsInBackground,
  };
}
