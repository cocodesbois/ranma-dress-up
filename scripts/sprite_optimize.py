"""Build the optimized runtime sprites from the Photoshop exports.

The PNG exports in images/sprites/ are the source of truth and are never modified.
Every PNG is converted to a cropped, downscaled WebP in images/optimized/, and the
crop offsets are written to images/optimized/manifest.js so the app can draw each
sprite at its original position on the shared document canvas.

- Sprites are cropped to the bounding box of their non-transparent pixels. This does
  not change the file size much (transparent areas compress well) but it removes
  most of the memory the browser needs to decode the image (4 bytes per pixel).
- Files whose name starts with "background" are never cropped: the whole image is
  kept and the app shows it in full.
- All exports must share the same canvas size (the Photoshop document size).

Only the standard library is needed to check the outputs; Pillow is needed to build.
"""
import hashlib
import json
import os
import struct
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPRITES_DIR = ROOT / "images" / "sprites"
OPTIMIZED_DIR = ROOT / "images" / "optimized"
MANIFEST_PATH = OPTIMIZED_DIR / "manifest.js"
MANIFEST_VARIABLE = "spriteManifest"
MANIFEST_VERSION = 1
FULL_FRAME_PREFIX = "background"

# Output scale relative to the Photoshop export. A canvas showing the whole document
# is pixel-perfect up to (document width x scale) device pixels, e.g. 0.5 -> 3321 px
# for a 6643 px document, which covers phones and laptops at 3x density with margin.
DEFAULT_SCALE = 0.5
DEFAULT_QUALITY = 85
DEFAULT_LOSSLESS = False


def relative_source(path):
    """Key used by the catalog: forward-slash path relative to the repository root."""
    return path.relative_to(ROOT).as_posix()


def source_files():
    return sorted(SPRITES_DIR.glob("*.png"))


def file_hash(path):
    digest = hashlib.sha1()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def png_size(path):
    """Read width and height from the PNG header without decoding the image."""
    with open(path, "rb") as handle:
        header = handle.read(24)
    if header[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"Not a PNG file: {path.name}")
    return struct.unpack(">II", header[16:24])


def load_manifest():
    if not MANIFEST_PATH.exists():
        return None
    text = MANIFEST_PATH.read_text(encoding="utf-8")
    return json.loads(text[text.index("{"):text.rindex("}") + 1])


def write_manifest(manifest):
    OPTIMIZED_DIR.mkdir(parents=True, exist_ok=True)
    body = json.dumps(manifest, indent=2)
    MANIFEST_PATH.write_text(
        "// Generated by scripts/optimize-sprites.py. Do not edit by hand.\n"
        f"const {MANIFEST_VARIABLE} = {body};\n\n"
        f"export default {MANIFEST_VARIABLE};\n",
        encoding="utf-8",
    )


def _optimize_one(args):
    """Worker: convert one PNG. Returns (source key, manifest entry or None, message)."""
    path_text, scale, quality, lossless = args
    from PIL import Image

    path = Path(path_text)
    output = OPTIMIZED_DIR / f"{path.stem}.webp"
    with Image.open(path) as opened:
        image = opened.convert("RGBA")
    alpha = image.getchannel("A")

    if path.stem.startswith(FULL_FRAME_PREFIX):
        box = (0, 0, image.width, image.height)
        if alpha.getextrema() == (255, 255):
            image = image.convert("RGB")
    else:
        box = alpha.getbbox()
        if box is None:
            return relative_source(path), None, f"WARNING: {path.name} is fully transparent, skipped"

    cropped = image.crop(box)
    target = (max(1, round(cropped.width * scale)), max(1, round(cropped.height * scale)))
    if target != cropped.size:
        cropped = cropped.resize(target, Image.LANCZOS)

    OPTIMIZED_DIR.mkdir(parents=True, exist_ok=True)
    cropped.save(output, "WEBP", quality=quality, lossless=lossless, method=4)

    entry = {
        "file": relative_source(output),
        "x": box[0],
        "y": box[1],
        "width": box[2] - box[0],
        "height": box[3] - box[1],
        "sourceHash": file_hash(path),
    }
    message = f"{path.name} -> {output.name} ({path.stat().st_size // 1024} KB -> {output.stat().st_size // 1024} KB)"
    return relative_source(path), entry, message


def optimize_all(scale=DEFAULT_SCALE, quality=DEFAULT_QUALITY, lossless=DEFAULT_LOSSLESS,
                 force=False, jobs=None, log=print):
    """Convert every sprite that is new or changed. Returns True when all went well."""
    try:
        import PIL  # noqa: F401
    except ImportError:
        sys.exit("Pillow is required: pip install pillow")

    sources = source_files()
    if not sources:
        sys.exit(f"No PNG files found in {SPRITES_DIR}")

    sizes = {path: png_size(path) for path in sources}
    counts = {}
    for size in sizes.values():
        counts[size] = counts.get(size, 0) + 1
    document_width, document_height = max(counts, key=counts.get)
    outliers = [f"  {path.name}: {w}x{h}" for path, (w, h) in sizes.items()
                if (w, h) != (document_width, document_height)]
    if outliers:
        sys.exit(
            f"All sprites must share the same canvas size (most files are {document_width}x{document_height}):\n"
            + "\n".join(outliers)
        )

    settings = {"scale": scale, "quality": quality, "lossless": lossless}
    previous = load_manifest() or {}
    reusable = {} if force or previous.get("settings") != settings else previous.get("sprites", {})
    if previous and previous.get("settings") != settings:
        log("Settings changed since the last run: rebuilding every sprite.")

    sprites = {}
    pending = []
    for path in sources:
        key = relative_source(path)
        entry = reusable.get(key)
        if entry and entry["sourceHash"] == file_hash(path) and (ROOT / entry["file"]).exists():
            sprites[key] = entry
        else:
            pending.append(path)

    ok = True
    if pending:
        jobs = jobs or min(4, os.cpu_count() or 1)
        work = [(str(path), scale, quality, lossless) for path in pending]
        log(f"Optimizing {len(pending)} sprite(s), {len(sprites)} already up to date...")
        if jobs > 1 and len(work) > 1:
            with ProcessPoolExecutor(max_workers=jobs) as pool:
                results = pool.map(_optimize_one, work)
                for key, entry, message in results:
                    log(f"  {message}")
                    if entry:
                        sprites[key] = entry
                    else:
                        ok = False
        else:
            for item in work:
                key, entry, message = _optimize_one(item)
                log(f"  {message}")
                if entry:
                    sprites[key] = entry
                else:
                    ok = False
    else:
        log(f"All {len(sprites)} sprites are already up to date.")

    manifest = {
        "version": MANIFEST_VERSION,
        "document": {"width": document_width, "height": document_height},
        "settings": settings,
        "sprites": dict(sorted(sprites.items())),
    }
    write_manifest(manifest)

    # Remove outputs whose PNG source no longer exists.
    expected = {ROOT / entry["file"] for entry in sprites.values()} | {MANIFEST_PATH}
    for stale in OPTIMIZED_DIR.glob("*.webp"):
        if stale not in expected:
            stale.unlink()
            log(f"  removed orphan {stale.name}")

    total = sum((ROOT / entry["file"]).stat().st_size for entry in sprites.values())
    log(f"Done: {len(sprites)} sprites, {total / 1e6:.1f} MB in images/optimized/.")
    return ok


def check():
    """Return a list of problems (empty when images/optimized/ matches images/sprites/)."""
    manifest = load_manifest()
    if manifest is None:
        return ["images/optimized/manifest.js is missing."]

    problems = []
    sources = source_files()
    known = set()
    document = manifest.get("document", {})
    for path in sources:
        key = relative_source(path)
        known.add(key)
        entry = manifest.get("sprites", {}).get(key)
        if entry is None:
            problems.append(f"{path.name}: not optimized yet.")
        elif entry["sourceHash"] != file_hash(path):
            problems.append(f"{path.name}: changed since it was optimized.")
        elif not (ROOT / entry["file"]).exists():
            problems.append(f"{path.name}: optimized file {entry['file']} is missing.")
        if png_size(path) != (document.get("width"), document.get("height")):
            problems.append(f"{path.name}: canvas size differs from the document size in the manifest.")
    for key in manifest.get("sprites", {}):
        if key not in known:
            problems.append(f"{key}: no longer exists but is still in the manifest.")
    return problems
